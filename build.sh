#!/usr/bin/env bash
# Builds the aquarevwater.us deliverables for the Specifications pages from the two masters in
# Marketing/Collateral/Installation Drawings. Re-run after any change to the masters, then push.
#
#   Page 1: /specifications  (Specifications & Installation Instructions document)
#     specifications.css / specifications.js / webflow-embed-specifications.html / preview.html
#   Page 2: /drawings        (Installation Drawing Set 100, eight sheets)
#     drawings.css / drawings.js / webflow-embed-drawings.html / preview-drawings.html
#   Both PDFs are copied here so GitHub Pages serves the download links.
#
# Each JS file injects its page markup into an empty container (#arsp or #ardw) and every style is
# scoped under that container, so Webflow's global styles never reach the page and vice versa.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
MASTER="/Users/jatley/Documents/Jeff Atley/Aquarev Water /Marketing/Collateral/Installation Drawings"
SPEC="$MASTER/AquaRev_Installation_Specifications_V1.html"
DRAW="$MASTER/AquaRev_Installation_Drawing_Set_V1.html"
SPEC_PDF="AquaRev_Installation_Specifications_V1.pdf"
DRAW_PDF="AquaRev_Installation_Drawing_Set_V1.pdf"
PAGES="https://jeffatley-web.github.io/aquarev_specifications"
SITE_SPEC="https://www.aquarevwater.us/specifications"
SITE_DRAW="https://www.aquarevwater.us/drawings"
ARTIFACT_SPEC="https://claude.ai/artifact/GAtq5SW7eoTDZ63EZjBkMD"
ARTIFACT_DRAW="https://claude.ai/artifact/MXuMZFfC1exQmvcYonPKDo"
STAMP="$(date +%Y%m%d%H%M)"
FONTS='https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@75..100,400..800&family=Source+Sans+3:ital,wght@0,400;0,600;1,400&family=IBM+Plex+Mono:wght@400;500&display=swap'

cd "$HERE"

# scope_css ROOT — reads CSS on stdin, writes CSS scoped under #ROOT on stdout
scope_css() {
  local root="$1"
  sed -E \
    -e 's#/\*[^*]*\*/##g' \
    -e "s/^:root\{/#${root}{/" \
    -e "s/:root:not\(\[data-theme=\"light\"\]\)\{/#${root}{/" \
    -e "s/^:root\[data-theme=\"dark\"\]\{/#${root}[data-theme=\"dark\"]{/" \
    -e '/^html\{scroll-behavior:smooth\}$/d' \
    -e '/^@media \(prefers-reduced-motion:reduce\)\{html\{scroll-behavior:auto\}\}$/d' \
    -e "s/^body\{/#${root}{/" \
    -e "s/position:sticky;top:0;z-index:5;/position:sticky;top:var(--${root}-sticky-top,0px);z-index:5;/" \
  | perl -e '
    my $css = do { local $/; <STDIN> }; my $root = shift @ARGV; my $out = "";
    while ($css =~ /\G([^{}]*)([{}])/gc) {
      my ($txt, $br) = ($1, $2);
      if ($br eq "{") {
        if ($txt =~ /^\s*@/) { $out .= $txt . "{"; }
        else {
          my ($lead) = $txt =~ /^(\s*)/;
          my @parts = map { my $s = $_; $s =~ s/^\s+|\s+$//g; ($s =~ /^#$root/ ? $s : "#$root $s") } split /,/, $txt;
          $out .= $lead . join(", ", @parts) . "{";
        }
      } else { $out .= $txt . "}"; }
    }
    $out .= substr($css, pos($css) // 0); print $out;
  ' "$root"
}

# rewrite_links — artifact URLs and local file links become site and GitHub Pages URLs
rewrite_links() {
  sed -E \
    -e "s|$ARTIFACT_SPEC|$SITE_SPEC|g" \
    -e "s|$ARTIFACT_DRAW|$SITE_DRAW|g" \
    -e "s|href=\"$SPEC_PDF\"|href=\"$PAGES/$SPEC_PDF\"|g" \
    -e "s|href=\"$DRAW_PDF\"|href=\"$PAGES/$DRAW_PDF\"|g" \
    -e 's|<a href="AquaRev_Installation_Drawing_Set_V1.html">Local web copy</a>||g' \
    -e 's| &#183; <a href="AquaRev_Installation_Drawing_Set_V1.html">local web copy</a>||g'
}

# ================= Page 1: specifications document =================
{
  echo "/* AquaRev Specifications & Installation Instructions. Generated by build.sh from the master; do not edit by hand. */"
  awk '/^<style>$/{f=1;next} /^<\/style>$/{f=0} f' "$SPEC" | scope_css arsp
} > specifications.css

{
  echo "/* AquaRev Specifications & Installation Instructions. Generated by build.sh from the master; do not edit by hand. */"
  echo "(function(){"
  echo "var root=document.getElementById('arsp'); if(!root) return;"
  echo "root.innerHTML=\`"
  awk '/^<div class="page">$/{f=1} f&&/^<script>$/{exit} f{print}' "$SPEC" | rewrite_links | sed -E 's/`/\\`/g'
  echo "\`;"
  # measure the site's sticky nav so the section navigator sits below it
  cat <<'EOF'
(function(){
  function navOffset(){
    var nav=document.querySelector('.w-nav, nav.w-nav'); var h=0;
    if(nav){ var cs=getComputedStyle(nav); if(cs.position==='sticky'||cs.position==='fixed'){ h=Math.round(nav.getBoundingClientRect().height); } }
    root.style.setProperty('--arsp-sticky-top', h+'px');
  }
  navOffset(); window.addEventListener('resize', navOffset); window.addEventListener('load', navOffset);
})();
EOF
  echo "if(location.hash){ var t=root.querySelector(decodeURIComponent(location.hash)); if(t){ setTimeout(function(){ t.scrollIntoView({block:'start'}); }, 80); } }"
  echo "})();"
} > specifications.js

cat > webflow-embed-specifications.html <<EOF
<!-- AquaRev Specifications & Installation Instructions. Paste this whole block into a Webflow Embed element on /specifications.
     CSS and JS are hosted on GitHub Pages; bump the ?v= values after pushing changes. -->
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="$PAGES/specifications.css?v=$STAMP">
<div id="arsp" data-theme="dark"></div>
<script defer src="$PAGES/specifications.js?v=$STAMP"></script>
EOF

cat > preview.html <<EOF
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Preview: AquaRev Specifications (local, mirrors the Webflow embed)</title>
<style>body{margin:0;background:#0E171E;font-family:sans-serif}</style>
</head>
<body>
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="specifications.css">
<div id="arsp" data-theme="dark"></div>
<script defer src="specifications.js"></script>
</body>
</html>
EOF

# ================= Page 2: drawing set =================
{
  echo "/* AquaRev Installation Drawing Set 100. Generated by build.sh from the master; do not edit by hand. */"
  awk '/^<style>$/{f=1;next} /^<\/style>$/{f=0} f' "$DRAW" | scope_css ardw
} > drawings.css

{
  echo "/* AquaRev Installation Drawing Set 100. Generated by build.sh from the master; do not edit by hand. */"
  echo "(function(){"
  echo "var root=document.getElementById('ardw'); if(!root) return;"
  echo "root.innerHTML=\`"
  # markup starts at the shared symbol defs (hidden svg) and runs to the page script
  awk '/^<!-- shared drafting symbols/{f=1} f&&/^<script>$/{exit} f{print}' "$DRAW" | rewrite_links | sed -E 's/`/\\`/g'
  echo "\`;"
  awk '/^<script>$/{f=1;next} /^<\/script>$/{f=0} f' "$DRAW" \
    | sed -E 's/document\.querySelectorAll\(/root.querySelectorAll(/g'
  echo "if(location.hash){ var t=root.querySelector(decodeURIComponent(location.hash)); if(t){ setTimeout(function(){ t.scrollIntoView({block:'start'}); }, 80); } }"
  echo "})();"
} > drawings.js

cat > webflow-embed-drawings.html <<EOF
<!-- AquaRev Installation Drawing Set 100. Paste this whole block into a Webflow Embed element on /drawings.
     CSS and JS are hosted on GitHub Pages; bump the ?v= values after pushing changes. -->
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="$PAGES/drawings.css?v=$STAMP">
<div id="ardw" data-theme="dark"></div>
<script defer src="$PAGES/drawings.js?v=$STAMP"></script>
EOF

cat > preview-drawings.html <<EOF
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Preview: AquaRev Installation Drawing Set (local, mirrors the Webflow embed)</title>
<style>body{margin:0;background:#0E171E;font-family:sans-serif}</style>
</head>
<body>
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="drawings.css">
<div id="ardw" data-theme="dark"></div>
<script defer src="drawings.js"></script>
</body>
</html>
EOF

cp -f "$MASTER/$SPEC_PDF" "$MASTER/$DRAW_PDF" .

wc -c specifications.css specifications.js drawings.css drawings.js webflow-embed-specifications.html webflow-embed-drawings.html "$SPEC_PDF" "$DRAW_PDF"
